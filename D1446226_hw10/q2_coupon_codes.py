def collect_codes(raw_codes, saved=None):
    result = list(saved) if saved is not None else []
    seen = set(result)

    for item in raw_codes:
        code = item.strip().upper()
        if not code:
            continue
        if code not in seen:
            seen.add(code)
            result.append(code)

    return result


