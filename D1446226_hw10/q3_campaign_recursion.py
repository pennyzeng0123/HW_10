def cumulative_spend(daily_spend, n):
    if n == 0:
        return 0
    return cumulative_spend(daily_spend, n - 1) + daily_spend[n - 1]


student_id = input("請輸入完整學號：").strip().upper()
tail = student_id[-3:]
a = int(student_id[-3])
b = int(student_id[-2])
c = int(student_id[-1])
s = a + b + c

daily_spend = [100 + 10 * a, 150 + 10 * b, 0,
               200 + 10 * c, 50 + 10 * s]
n = min(3 + c, len(daily_spend))

print(f"學號：{student_id}")
print(f"每日費用：{daily_spend}")
print(f"指定 n：{n}")
print(f"前 {n} 天累計費用：{cumulative_spend(daily_spend, n)}")

for k in range(0, 6):
    print(f"前 {k} 天累計費用：{cumulative_spend(daily_spend, k)}")

print("cumulative_spend([], 0) ->", cumulative_spend([], 0))