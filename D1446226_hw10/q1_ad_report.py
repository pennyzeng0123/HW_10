def ad_report(impressions, clicks, target=3.0):
    if impressions == 0:
        return (None, False)
    ctr = clicks / impressions * 100
    passed = ctr >= target
    return (ctr, passed)


student_id = input("請輸入完整學號：").strip().upper()
tail = student_id[-3:]
a = int(student_id[-3])
b = int(student_id[-2])
c = int(student_id[-1])
s = a + b + c

ads = [
    ("搜尋廣告", 1000 + 100 * a, 30 + 5 * b),
    ("社群廣告", 1200 + 100 * b, 24 + 4 * c),
    ("影音廣告", 0, 0),
]
target = 2.5 + 0.1 * c

print(f"學號：{student_id}（後三碼：{tail}，s={s}）")
print(f"個人門檻：{target:.2f}%")

passed_count = 0

for name, impressions, clicks in ads:
    ctr, passed = ad_report(impressions, clicks, target=target)
    if passed:
        passed_count += 1
    ctr_str = f"{ctr:.2f}%" if ctr is not None else "無曝光"
    status_str = "達標" if passed else "未達標"
    print(f"{name} | 曝光：{impressions} | 點擊：{clicks} | CTR：{ctr_str} | 達標狀態：{status_str}")

print(f"達標廣告數：{passed_count}")

print("ad_report(1000, 30) ->", ad_report(1000, 30))
print("ad_report(1000, 0) ->", ad_report(1000, 0))